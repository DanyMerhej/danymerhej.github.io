/**
 * Downloads the latin + latin-ext woff2 subsets for the site's four families and
 * writes src/fonts.css pointing at local copies.
 *
 * Self-hosting keeps the page independent of fonts.googleapis.com: one less
 * third party in the critical path, and no request leaves the visitor's browser.
 *
 * Run manually when a family or weight changes:  node scripts/fetch-fonts.mjs
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fontsDir = resolve(here, '..', 'public', 'fonts');
const cssOut = resolve(here, '..', 'src', 'fonts.css');

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';

const HREF =
  'https://fonts.googleapis.com/css2?' +
  [
    'family=Syne:wght@600..800',
    'family=Inter:wght@300..600',
    'family=Instrument+Serif:ital@0;1',
    'family=JetBrains+Mono:wght@400..500',
  ].join('&') +
  '&display=swap';

// Only the two subsets this site actually needs.
const LATIN = 'U+0000-00FF';
const LATIN_EXT = 'U+0100-02BA';

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const css = await (await fetch(HREF, { headers: { 'User-Agent': UA } })).text();

await mkdir(fontsDir, { recursive: true });

const blocks = css.split('@font-face').slice(1);
const kept = [];

for (const block of blocks) {
  const range = block.match(/unicode-range:\s*([^;]+);/)?.[1] ?? '';
  if (!range.includes(LATIN) && !range.includes(LATIN_EXT)) continue;

  const family = block.match(/font-family:\s*'([^']+)'/)?.[1];
  const url = block.match(/url\((https:[^)]+\.woff2)\)/)?.[1];
  if (!family || !url) continue;

  const style = block.match(/font-style:\s*([^;]+);/)?.[1].trim() ?? 'normal';
  const weight = block.match(/font-weight:\s*([^;]+);/)?.[1].trim() ?? '400';
  const stretch = block.match(/font-stretch:\s*([^;]+);/)?.[1].trim();

  const subset = range.includes(LATIN) ? 'latin' : 'latin-ext';
  const file = `${slug(family)}-${slug(style)}-${slug(weight)}-${subset}.woff2`;

  const bytes = Buffer.from(await (await fetch(url, { headers: { 'User-Agent': UA } })).arrayBuffer());
  await writeFile(resolve(fontsDir, file), bytes);

  kept.push(
    [
      '@font-face {',
      `  font-family: '${family}';`,
      `  font-style: ${style};`,
      `  font-weight: ${weight};`,
      stretch ? `  font-stretch: ${stretch};` : null,
      '  font-display: swap;',
      `  src: url('/fonts/${file}') format('woff2');`,
      `  unicode-range: ${range};`,
      '}',
    ]
      .filter(Boolean)
      .join('\n'),
  );

  console.log(`↓ ${file}`);
}

await writeFile(
  cssOut,
  `/* Generated by scripts/fetch-fonts.mjs. Do not edit by hand. */\n\n${kept.join('\n\n')}\n`,
);

console.log(`\nWrote ${kept.length} faces to src/fonts.css`);
